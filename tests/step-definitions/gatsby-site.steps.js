'use strict';

// Step definitions for the build and the runtime of a Gatsby site: who made
// the page, whether the production build is served, whether React hydrated
// the page without errors, whether the page belongs to the current build, the
// Head API, the web app manifest and the page without JavaScript.
//
// The step phrases do not name the framework where the sentence reads well
// without it; what they check underneath is Gatsby's own behaviour, described
// in `gatsby-helpers.js`.

const { Then } = require('@cucumber/cucumber');
const {
  budget, escapeRegExp, waitForHydration, poll, actOrExplain, friendly,
} = require('./gatsby-helpers');

const GENERATOR_HINT = 'Gatsby writes `<meta name="generator" content="Gatsby X.Y.Z">` into the pages of a production build (`gatsby build`); the development server (`gatsby develop`), another tool or a `<head>` that strips the tag does not carry it.';

/**
 * Wait until the page's <meta name="generator"> content satisfies `test` (or,
 * with `notCase`, does not). Throws a friendly error with the content found.
 */
async function waitForGenerator(world, notCase, test, { message, hint = GENERATOR_HINT }) {
  const timeout = budget(world);
  try {
    await world.page.waitForFunction(
      ({ src, want }) => {
        const meta = document.querySelector('meta[name="generator"]');
        const content = meta ? meta.getAttribute('content') || '' : '';
        return Boolean(new RegExp(src, 'i').test(content)) === want;
      },
      { src: test.source, want: !notCase },
      { timeout }
    );
  } catch {
    const content = await world.page.locator('meta[name="generator"]').first().getAttribute('content').catch(() => null);
    throw friendly({
      message: `${message} ${content === null ? 'No <meta name="generator"> tag was found.' : `The generator meta tag is "${content}".`}`,
      hint,
    });
  }
}

/**
 * Assert the current page was (or was not) built by Gatsby, by its generator
 * meta tag. The markup phrasing ("the Gatsby generator meta tag") and the
 * site phrasing ("generated by Gatsby") are one step.
 *
 * Example #1: Then the page should be generated by Gatsby
 * Example #2: Then we should see the Gatsby generator meta tag
 * Example #3: And the page should not be generated by Gatsby
 * Example #4: Then should see the Gatsby generator meta tag
 * Example #5: Then page should be generated by Gatsby
 */
Then(/^(?:(?:I |we )*should( not)* see the Gatsby generator meta tag|(?:the )?page should( not)* be generated by Gatsby)$/, async function (notSee, notGenerated) {
  const notCase = notSee || notGenerated;
  await waitForGenerator(this, notCase, /^gatsby/, {
    message: notCase
      ? 'Expected the page not to be generated by Gatsby, but it is.'
      : 'Expected the page to be generated by Gatsby (a generator meta tag starting with "Gatsby").',
  });
});

/**
 * Assert the page was (or was not) built by a version of Gatsby. The version
 * is matched from its start, so "5" matches "Gatsby 5.16.1" and "5.16"
 * matches it too.
 *
 * Example #1: Then the page should be generated by Gatsby version "5"
 * Example #2: Then the page should be generated by Gatsby version "5.16"
 * Example #3: And the page should be generated by Gatsby version "5.16.1"
 * Example #4: But the page should not be generated by Gatsby version "4"
 * Example #5: Then page should be generated by Gatsby version "5"
 */
Then(/^(?:the )?page should( not)* be generated by Gatsby version "([^"]*)?"$/, async function (notCase, version) {
  await waitForGenerator(this, notCase, new RegExp(`^gatsby ${escapeRegExp(version)}`), {
    message: notCase
      ? `Expected the page not to be generated by Gatsby version "${version}", but it is.`
      : `Expected the page to be generated by Gatsby version "${version}".`,
    hint: 'The version is matched from its start against the part after "Gatsby " in the generator meta tag; check the Gatsby version in the site\'s package.json.',
  });
});

/**
 * Assert the page was (or was not) served by a production build. A production
 * build sets the build hash (`window.___webpackCompilationHash`) and loads
 * hashed scripts; `gatsby develop` sets no hash and loads `socket.io.js` and
 * unhashed bundles for hot reloading, which also keeps the page from going
 * network-idle.
 *
 * Example #1: Then the site should be a production build
 * Example #2: And the site should be a production build
 * Example #3: But the site should not be a production build
 * Example #4: Then site should be a production build
 * Example #5: Then the site should be served as a production build
 */
Then(/^(?:the )?site should( not)* be (?:served as )?a production build$/, async function (notCase) {
  const state = () => this.page.evaluate(() => ({
    hash: typeof window.___webpackCompilationHash === 'string' && window.___webpackCompilationHash !== '',
    socket: Boolean(document.querySelector('script[src*="socket.io"]')),
  }));
  let seen;
  const ok = await poll(this, async () => {
    seen = await state();
    return (seen.hash && !seen.socket) === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase
        ? 'Expected the development server, but the page is a production build (it has a build hash and no hot-reload script).'
        : `Expected a production build, but the page looks like \`gatsby develop\` (build hash: ${seen.hash ? 'yes' : 'no'}, hot-reload script: ${seen.socket ? 'yes' : 'no'}).`,
      hint: 'Run `gatsby build` and serve the result with `gatsby serve`; the suite needs the production build, and LAUNCH_URL must point at it.',
    });
  }
});

/**
 * Assert React has (or has not) hydrated the current page: it has attached to
 * `#___gatsby` and to the page elements, so the links and the page scripts
 * work. The server HTML alone does not count: it carries `#___gatsby` before
 * any script has run.
 *
 * Example #1: Then I should see a hydrated page
 * Example #2: Then we should see a hydrated page
 * Example #3: And I should not see a hydrated page
 * Example #4: Then should see a hydrated page
 * Example #5: And we should see a hydrated page
 */
Then(/^(I |we )*should( not)* see a hydrated page$/, async function (pronounCase, notCase) {
  const timeout = budget(this);
  let state;
  if (notCase) {
    state = await this.page.evaluate(() => ({ hydrated: Object.keys(document.getElementById('___gatsby') || {}).some((key) => key.startsWith('__reactContainer$')) }));
    if (state.hydrated) {
      throw friendly({
        message: 'Expected a page that React has not hydrated, but React has attached to it.',
        hint: 'To look at a page before hydration, load it with JavaScript turned off (see "without JavaScript").',
      });
    }
    return;
  }
  state = await waitForHydration(this, timeout);
  if (state.hydrated) return;
  let message;
  let hint;
  if (!state.root) {
    message = 'This page has no #___gatsby element, so it is not a Gatsby page.';
    hint = 'Check LAUNCH_URL and the path: a proxy error page, a redirect or another site does not carry the Gatsby root.';
  } else if (!state.loader) {
    message = `The page HTML is there, but the Gatsby runtime did not start within ${timeout} ms (no window.___loader).`;
    hint = 'The page scripts did not load or failed: check the browser console and the network for the app-*.js and framework-*.js bundles, and that the build is served from its `public/` folder.';
  } else {
    message = `The Gatsby runtime started, but React did not attach to the page within ${timeout} ms.`;
    hint = 'Look for "Hydration" or "Minified React error" messages in the browser console; a page that renders differently on the server and in the browser keeps the page from hydrating.';
  }
  throw friendly({ message, hint });
});

/**
 * Assert the page was hydrated without (or, to prove the check, with)
 * hydration errors. React reports a mismatch between the HTML of the server
 * and the first browser render as an error (#418, #423, #425 in production);
 * the step waits for hydration, then reads the errors recorded since the
 * scenario started.
 *
 * Example #1: Then there should be no hydration errors
 * Example #2: And there should be no hydration errors
 * Example #3: But there should be hydration errors
 * Example #4: Then there should be no hydration errors
 * Example #5: And there should be hydration errors
 */
Then(/^there should be (no )?hydration errors$/, async function (noCase) {
  await waitForHydration(this);
  if (noCase) {
    await this.page.waitForTimeout(500);
    const errors = this.gatsbyHydrationErrors || [];
    if (errors.length) {
      throw friendly({
        message: `React reported ${errors.length} hydration error(s) on this page:\n  ${errors.join('\n  ')}`,
        hint: 'The server HTML and the first browser render differ. Typical causes: `window`, `Date.now()` or `Math.random()` read while rendering, or markup nested in a way the browser rewrites. Move browser-only values into `useEffect`.',
      });
    }
    return;
  }
  const found = await poll(this, async () => (this.gatsbyHydrationErrors || []).length > 0, 3000);
  if (!found) {
    throw friendly({
      message: 'Expected hydration errors on this page, but React reported none.',
      hint: 'This phrasing proves the check can fail: use it on a page that is known to render differently on the server and in the browser.',
    });
  }
});

/**
 * Assert the page does (or does not) come from the current build. Gatsby
 * inlines the build hash in every page (`window.___webpackCompilationHash`)
 * and publishes it as `page-data/app-data.json`; when the two differ, the
 * page was served from an older deploy (a stale cache or a half-uploaded
 * site) and Gatsby reloads it once.
 *
 * Example #1: Then the page should be from the current build
 * Example #2: And the page should be from the current build
 * Example #3: But the page should not be from the current build
 * Example #4: Then page should be from the current build
 * Example #5: And the page should be from the current build
 */
Then(/^(?:the )?page should( not)* be from the current build$/, async function (notCase) {
  const url = new URL('/page-data/app-data.json', this.page.url()).toString();
  const hint = 'Compare the hash in the page (`window.___webpackCompilationHash`) with `page-data/app-data.json`; a mismatch means the HTML and the data come from different builds, usually a CDN or browser cache after a deploy.';
  let pageHash;
  let siteHash;
  const ok = await poll(this, async () => {
    pageHash = await this.page.evaluate(() => window.___webpackCompilationHash);
    const response = await this.page.request.get(url, { timeout: budget(this) }).catch(() => null);
    const body = response && response.status() === 200 ? await response.json().catch(() => null) : null;
    siteHash = body && body.webpackCompilationHash;
    return Boolean(pageHash) && Boolean(siteHash) && (pageHash === siteHash) === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase
        ? `Expected a page from an older build, but the page and ${url} both carry "${pageHash}".`
        : `The page carries the build hash "${pageHash || 'none'}" but ${url} says "${siteHash || 'none'}".`,
      hint,
    });
  }
});

/**
 * Assert the page head is (or is not) written by Gatsby's Head API: the tags
 * that the `Head` export renders carry `data-gatsby-head="true"`, and Gatsby
 * replaces them on every client-side navigation. Tags from react-helmet or a
 * hand-written `<head>` do not carry it.
 *
 * Example #1: Then the page head should be set by the Head API
 * Example #2: And the page head should be set by the Head API
 * Example #3: But the page head should not be set by the Head API
 * Example #4: Then page head should be set by the Head API
 * Example #5: And the head should be set by the Head API
 */
Then(/^(?:the )?(?:page )?head should( not)* be set by the Head API$/, async function (notCase) {
  const ok = await poll(this, async () => {
    const count = await this.page.locator('head [data-gatsby-head]').count();
    return (count > 0) === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase
        ? 'Expected a head that the Head API does not write, but the head has data-gatsby-head tags.'
        : 'Expected tags with data-gatsby-head="true" in the page head, but there are none.',
      hint: 'Export `Head` from the page (or the template) and render <title> and <meta> in it; react-helmet and gatsby-plugin-react-helmet write other attributes.',
    });
  }
});

/**
 * Assert the page links a valid web app manifest (gatsby-plugin-manifest): it
 * is JSON, it has a name and a start URL, and every icon it lists is served as
 * an image.
 *
 * Example #1: Then the web app manifest should be valid
 * Example #2: And the web app manifest should be valid
 * Example #3: Then web app manifest should be valid
 * Example #4: And the manifest should be valid
 * Example #5: Then we should see a valid web app manifest
 */
Then(/^(?:(?:I |we )*should see a valid web app manifest|(?:the )?(?:web app )?manifest should be valid)$/, async function () {
  const hint = 'Add gatsby-plugin-manifest to gatsby-config with a name, a start_url and an icon; the plugin writes manifest.webmanifest and the <link rel="manifest"> tag.';
  const href = await this.page.locator('link[rel="manifest"]').first().getAttribute('href').catch(() => null);
  if (!href) {
    throw friendly({ message: 'The page has no <link rel="manifest"> tag.', hint });
  }
  const manifestUrl = new URL(href, this.page.url()).toString();
  const response = await actOrExplain('fetch', manifestUrl, hint, () => this.page.request.get(manifestUrl, { timeout: budget(this) }));
  if (response.status() !== 200) {
    throw friendly({ message: `Expected 200 fetching the manifest ${manifestUrl}, got ${response.status()}.`, hint });
  }
  const manifest = await response.json().catch(() => null);
  if (!manifest || typeof manifest !== 'object') {
    throw friendly({ message: `The manifest ${manifestUrl} is not valid JSON.`, hint });
  }
  const problems = [];
  if (!manifest.name && !manifest.short_name) problems.push('it has no "name" or "short_name"');
  if (!manifest.start_url) problems.push('it has no "start_url"');
  if (!Array.isArray(manifest.icons) || manifest.icons.length === 0) problems.push('it lists no "icons"');
  for (const icon of Array.isArray(manifest.icons) ? manifest.icons : []) {
    const iconUrl = new URL(icon.src, manifestUrl).toString();
    const result = await this.page.request.get(iconUrl, { timeout: budget(this) }).catch(() => null);
    const type = result ? result.headers()['content-type'] || '' : '';
    if (!result || result.status() !== 200 || !/^image\//.test(type)) {
      problems.push(`the icon ${icon.src} is not served as an image (${result ? `HTTP ${result.status()}, ${type || 'no content type'}` : 'request failed'})`);
    }
  }
  if (problems.length) {
    throw friendly({ message: `The web app manifest ${manifestUrl} is not valid: ${problems.join('; ')}.`, hint });
  }
});

/**
 * Assert a text is (or is not) in the page when JavaScript is turned off. The
 * page is loaded again in a separate browser context without JavaScript, so
 * the step sees what a search engine, a feed reader or a visitor whose
 * scripts failed gets: the static HTML Gatsby rendered at build time (or on
 * the server, for server-side rendered pages).
 *
 * Example #1: Then I should see "Welcome to Gatsby!" without JavaScript
 * Example #2: Then we should see "Hi from the second page" without JavaScript
 * Example #3: And I should not see "Rendered in the browser" without JavaScript
 * Example #4: Then should see "Page two" without JavaScript
 * Example #5: And we should see "A long page" without JavaScript
 */
Then(/^(I |we )*should( not)* see "([^"]*)?" without JavaScript$/, async function (pronounCase, notCase, text) {
  const url = this.page.url();
  const context = await this.playwrightBrowser.newContext({ javaScriptEnabled: false });
  try {
    const page = await context.newPage();
    await actOrExplain('open without JavaScript', url, 'The page could not be loaded in a context without JavaScript; check the address is reachable.', () => page.goto(url, { waitUntil: 'domcontentloaded', timeout: budget(this) }));
    const body = await page.locator('body').innerText();
    const found = body.includes(text);
    if (found === Boolean(notCase)) {
      throw friendly({
        message: notCase
          ? `Expected "${text}" to be missing from the page without JavaScript, but it is there.`
          : `Expected "${text}" in the page without JavaScript, but the page text is: "${body.replace(/\s+/g, ' ').slice(0, 160)}".`,
        hint: 'Gatsby renders pages to HTML at build time; text that appears only after a script has run (a client-side fetch, `useEffect`, `window`) is not in the HTML that search engines and no-script visitors get.',
      });
    }
  } finally {
    await context.close();
  }
});
